function [peak_valid, peak_center, peak_std, peak_accum, power_norm] = get_accumulated_peaks(power_data)
    num_peaks = 4;
    peak_threshold = 100;
    peak_max_half_width = 30;
    peak_power_hyst_factor = 0.1;

    peak_center = zeros(num_peaks, 1);
    peak_accum  = zeros(num_peaks, 1);
    peak_std    = zeros(num_peaks, 1);
    peak_valid  = false(num_peaks, 1);

    noise_floor = median(power_data);
    if noise_floor <= 0
        return
    end
    power_norm = power_data(:) / noise_floor;   % column
    N = numel(power_norm);

    for i_peak = 1:num_peaks
        [m, p] = max(power_norm);               % p is 1-based
        if power_norm(p) > peak_threshold
            peak_valid(i_peak) = true;

            inclusion_threshold = 2; %power_norm(p) * peak_power_hyst_factor;
            peak_accum_power    = power_norm(p);
            peak_accum_moment_1 = p * power_norm(p);
            peak_accum_moment_2 = p * p * power_norm(p);

            power_norm(p) = 1.0;
            upper_done = false;
            lower_done = false;

            for i_clear = 1:(peak_max_half_width - 1)
                upper_index = p + i_clear;
                lower_index = p - i_clear;

                if upper_index <= N && power_norm(upper_index) > inclusion_threshold && ~upper_done
                    peak_accum_power    = peak_accum_power    + power_norm(upper_index);
                    peak_accum_moment_1 = peak_accum_moment_1 + upper_index * power_norm(upper_index);
                    peak_accum_moment_2 = peak_accum_moment_2 + upper_index * upper_index * power_norm(upper_index);
                    power_norm(upper_index) = 1.0;
                else
                    upper_done = true;
                end

                if lower_index >= 1 && power_norm(lower_index) > inclusion_threshold && ~lower_done
                    peak_accum_power    = peak_accum_power    + power_norm(lower_index);
                    peak_accum_moment_1 = peak_accum_moment_1 + lower_index * power_norm(lower_index);
                    peak_accum_moment_2 = peak_accum_moment_2 + lower_index * lower_index * power_norm(lower_index);
                    power_norm(lower_index) = 1.0;
                else
                    lower_done = true;
                end
            end

            peak_center(i_peak) = peak_accum_moment_1 / peak_accum_power;
            var = peak_accum_moment_2 / peak_accum_power - peak_center(i_peak)^2;
            peak_std(i_peak)    = sqrt(max(0, var));
            peak_accum(i_peak)  = peak_accum_power;
        else
            break
        end
    end
